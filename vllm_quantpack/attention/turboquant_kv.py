"""Fixes for vLLM's TurboQuant KV cache with FP8 keys (--kv-cache-dtype turboquant_k8v4).

Defects found with Qwen3.8-27B (head 256) on vLLM 0.33:

1. Keys saturate below sm_89. TurboQuant stores the keys as FP8 without a scale. Triton has no E4M3 type
   (fp8e4nv) before Ada, so on Ampere the kernels use fp8e4b15, whose range is +-1.875: larger keys are clipped
   and the model loses the context. The patch encodes and decodes E4M3 with integer operations on those GPUs
   (round to nearest even, saturating at +-448), so the cache holds the same bytes as on Ada / Blackwell.

2. Garbage with speculative decoding (MTP / EAGLE). The backend only treats one-token steps as decode; a
   verification step (1 + draft tokens per request) is a uniform batch, so vLLM replays it from a full CUDA graph,
   but it goes through the prefill code, which picks its branch and builds the context lengths in Python: the graph
   keeps the values of the capture (a context of one token). The patch sends steps of up to 1 + draft tokens per
   request to the decode kernel, one row per query token, with the lengths computed on the GPU.

The kernel copy is produced by exact text edits of the installed vLLM source. If any anchor is missing (another vLLM
version) nothing is patched and the stock kernels stay. VLLM_QUANTPACK_TURBOQUANT=0 disables the patch.
"""
import importlib
import inspect
import os
import textwrap

from .int4_kv import _edit, _load

DECODE_MODULE = "vllm.v1.attention.ops.triton_turboquant_decode"
STORE_MODULE = "vllm.v1.attention.ops.triton_turboquant_store"
BACKEND_MODULE = "vllm.v1.attention.backends.turboquant_attn"

E4M3 = '''
@triton.jit
def _qp_e4m3_decode(b):
    """uint8 E4M3 bytes -> float32."""
    i = b.to(tl.int32)
    e = (i >> 3) & 15
    m = i & 7
    normal = (((e + 120) << 23) | (m << 20)).to(tl.float32, bitcast=True)
    mag = tl.where(e == 0, m.to(tl.float32) * 0.001953125, normal)
    return tl.where(i >= 128, -mag, mag)


@triton.jit
def _qp_e4m3_encode(x):
    """float32 -> uint8 E4M3 bytes, round to nearest even, saturating at +-448."""
    a = tl.minimum(tl.abs(x), 448.0)
    bits = a.to(tl.int32, bitcast=True)
    r = bits + 524287 + ((bits >> 20) & 1)
    normal = (r >> 20) - 960
    t = a * 512.0
    f = tl.floor(t)
    d = t - f
    fi = f.to(tl.int32)
    sub = fi + tl.where((d > 0.5) | ((d == 0.5) & ((fi & 1) == 1)), 1, 0)
    mag = tl.where(a < 0.015625, sub, normal)
    sign = (x.to(tl.int32, bitcast=True) >> 24) & 128
    return (mag | sign).to(tl.uint8)
'''

# (old, new): each `old` must occur exactly once in the stock kernel source.
DECODE_EDITS = (("k_raw.to(tl.float8e4b15, bitcast=True).to(tl.float32)", "_qp_e4m3_decode(k_raw)"),)
STORE_EDITS = (
    ("    k_fp8 = k_vals.to(tl.float8e4b15) if FP8_E4B15 else k_vals.to(tl.float8e4nv)\n"
     "    k_bytes = k_fp8.to(tl.uint8, bitcast=True)\n",
     "    if FP8_E4B15:\n"
     "        k_bytes = _qp_e4m3_encode(k_vals)\n"
     "    else:\n"
     "        k_bytes = k_vals.to(tl.float8e4nv).to(tl.uint8, bitcast=True)\n"),
)
# kernel name -> (module that defines it, edits)
KERNELS = {
    "_tq_decode_stage1": (DECODE_MODULE, DECODE_EDITS),
    "_tq_full_dequant_kv": (DECODE_MODULE, DECODE_EDITS),
    "_tq_fused_store_fp8": (STORE_MODULE, STORE_EDITS),
}


def build_source(modules):
    """Source of the replacement kernels; `modules` maps module name -> stock module object."""
    parts = ["# Generated by vllm_quantpack.attention.turboquant_kv from the installed vLLM source: do not edit.\n"]
    for name in (DECODE_MODULE, STORE_MODULE):
        parts.append(f"import {name} as _stock\n"
                     "globals().update({k: v for k, v in vars(_stock).items() if not k.startswith('__')})\n")
    parts.append(E4M3)
    for kernel, (module, edits) in KERNELS.items():
        src = textwrap.dedent(inspect.getsource(getattr(modules[module], kernel).fn))
        parts.append("\n\n" + _edit(src, edits, f"TurboQuant {kernel}"))   # keeps its @triton.jit decorator
    return "".join(parts)


def needs_e4m3_emulation():
    """True when a visible CUDA device has no fp8e4nv in Triton (compute capability below 8.9)."""
    import torch
    if not torch.cuda.is_available():
        return False
    return any(torch.cuda.get_device_capability(i) < (8, 9) for i in range(torch.cuda.device_count()))


def token_rows(query_start_loc, seq_lens, block_table, num_tokens):
    """One decode row per query token: (context length seen by the token, block table row), on the GPU.

    query_start_loc [R + 1], seq_lens [R] (context length including the request's query tokens), block_table [R, W].
    Tokens past the last request (CUDA graph padding) repeat the last request.
    """
    import torch
    tok = torch.arange(num_tokens, device=query_start_loc.device, dtype=query_start_loc.dtype)
    ends = query_start_loc[1:].contiguous()
    req = torch.searchsorted(ends, tok, right=True).clamp_(max=ends.shape[0] - 1)
    after = (ends[req] - 1 - tok).clamp_(min=0)          # query tokens of the same request that follow this one
    lens = (seq_lens[req] - after.to(seq_lens.dtype)).clamp_(min=1)
    return lens, block_table.index_select(0, req)


def _patch_spec_decode(backend, logger):
    """Verification steps of speculative decoding through the decode kernel (defect 2)."""
    impl, builder = backend.TurboQuantAttentionImpl, backend.TurboQuantMetadataBuilder
    if getattr(impl._prefill_attention, "_quantpack", False):
        return True
    from vllm.config import get_current_vllm_config
    from vllm.v1.attention.backend import max_decode_query_len
    stock_prefill, stock_capture, stock_reserve = (impl._prefill_attention, impl._max_capture_batch_size,
                                                   builder._reserve_workspace)

    state = {}      # query tokens per request in a decode step; the builder knows the config, the forward does not

    def limit():
        if "limit" not in state:
            try:
                state["limit"] = max_decode_query_len(get_current_vllm_config())
            except Exception:
                return 1
        return state["limit"]

    def _prefill_attention(self, query, key, value, kv_cache, attn_metadata, Pi, centroids, PiT=None, layer=None):
        if not 1 < attn_metadata.max_query_len <= limit():
            return stock_prefill(self, query, key, value, kv_cache, attn_metadata, Pi, centroids, PiT, layer=layer)
        n = query.shape[0]
        if not state.get("logged"):
            state["logged"] = True
            logger.info("vllm-quantpack: TurboQuant decode kernel on a speculative step (%d query tokens, up to %d per "
                        "request)", n, limit())
        lens, table = token_rows(attn_metadata.query_start_loc, attn_metadata.seq_lens, attn_metadata.block_table, n)
        meta = backend.TurboQuantMetadata(
            seq_lens=lens, slot_mapping=attn_metadata.slot_mapping, block_table=table,
            query_start_loc=attn_metadata.query_start_loc, num_actual_tokens=n, max_query_len=1,
            max_seq_len=attn_metadata.max_seq_len, is_prefill=False)
        return self._decode_attention(query, kv_cache, meta, Pi, centroids, PiT, layer)

    def _max_capture_batch_size(self):
        return stock_capture(self) * limit()          # decode rows are query tokens, not requests

    def _reserve_workspace(self):
        stock_reserve(self)
        state["limit"] = max_decode_query_len(self.vllm_config)
        rows = self.vllm_config.scheduler_config.max_num_seqs * max_decode_query_len(self.vllm_config)
        if rows == self.vllm_config.scheduler_config.max_num_seqs:
            return
        import torch
        from vllm.v1.worker.workspace import current_workspace_manager, is_workspace_manager_initialized
        if not is_workspace_manager_initialized():
            return
        model = self.vllm_config.model_config
        heads = model.get_num_attention_heads(self.vllm_config.parallel_config)
        head = self.kv_cache_spec.head_size
        splits = self.vllm_config.attention_config.tq_max_kv_splits_for_cuda_graph
        current_workspace_manager().get_simultaneous(
            ((rows, heads, splits, head + 1), torch.float32), ((rows, heads, head), model.dtype),
            ((rows, heads), torch.float32))

    _prefill_attention._quantpack = True
    impl._prefill_attention = _prefill_attention
    impl._max_capture_batch_size = _max_capture_batch_size
    builder._reserve_workspace = _reserve_workspace
    logger.info("vllm-quantpack: TurboQuant speculative-decoding steps use the decode kernel (CUDA-graph safe)")
    return True


def patch_turboquant_kv(logger):
    if os.environ.get("VLLM_QUANTPACK_TURBOQUANT", "1") == "0":
        return False
    try:
        modules = {name: importlib.import_module(name) for name in (DECODE_MODULE, STORE_MODULE)}
        backend = importlib.import_module(BACKEND_MODULE)
    except Exception as e:      # vLLM without TurboQuant
        logger.debug("vllm-quantpack: TurboQuant KV attention not patched (%s)", e)
        return False
    try:
        spec = _patch_spec_decode(backend, logger)
    except Exception as e:
        logger.warning("vllm-quantpack: TurboQuant speculative decoding left stock (%s)", e)
        spec = False
    return _patch_e4m3(modules, backend, logger) or spec


def _patch_e4m3(modules, backend, logger):
    """E4M3 keys below sm_89 (defect 1)."""
    if getattr(modules[STORE_MODULE]._tq_fused_store_fp8, "_quantpack", False):
        return True
    try:
        if not needs_e4m3_emulation():
            return False
        gen = _load(build_source(modules), "turboquant_kv")
    except Exception as e:
        logger.warning("vllm-quantpack: TurboQuant KV attention left stock (%s)", e)
        return False
    for kernel, (module, _) in KERNELS.items():
        new = getattr(gen, kernel)
        new._quantpack = True
        setattr(modules[module], kernel, new)       # the launchers look the kernels up in their module globals
    backend._tq_full_dequant_kv = gen._tq_full_dequant_kv   # imported by name into the backend
    logger.info("vllm-quantpack: TurboQuant FP8 keys stored as E4M3 on this GPU (integer encode/decode; vLLM uses "
                "fp8e4b15 below sm_89, which clips keys at +-1.875)")
    return True
