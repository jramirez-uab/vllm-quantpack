"""k8v4_per_token_head KV cache: int8 keys and int4 values, on vLLM's Triton backend.

`--kv-cache-dtype k8v4_per_token_head` stores, per (token, KV head), the key as int8 with one fp32 scale and the
value exactly as `int4_per_token_head` does (two nibbles per byte, fp32 scale with the 4-bit zero point in its low
mantissa bits). Both are stored in the randomized-Hadamard domain, like the int4 cache. The attention scores are the
part of the int4 cache that loses quality (keys at 4 bits); the values tolerate 4 bits better. Measured against a
bf16 cache on a Qwen3.8-27B fine-tune (KL divergence of the next-token distribution, 250k-token context): int8
0.0011, fp8 0.0023, this format 0.0032, vLLM's turboquant_k8v4 0.0065, int4 0.0093.

Page cell, head size hs: [K hs int8 | K scale f32 | V hs/2 bytes | V scale f32] = 1.5 hs + 8 bytes (392 at hs 256;
int4 264, fp8_per_token_head 520).

How it plugs into vLLM without touching it:
- the dtype is registered with vLLM's `register_kv_cache_dtype`. Its handler answers KVQuantMode.INT4_PER_TOKEN_HEAD,
  so every generic per-token-head path (dynamic scales, Triton backend, the packed attention dispatch) is reused,
  and storage dtype int8 (the stock int4 cache is uint8): that pair identifies the format where vLLM passes no
  dtype string (the attention spec, the cache views);
- TritonAttentionBackend.customize_spec sizes the cell, TritonAttentionImpl gets the key / value / scale views;
- the store and the read kernels are the int4 ones with the key half replaced (store: k8v4_ops._store_k8v4; read:
  generated by int4_kv from the installed vLLM source, like the int4 fixes).

It needs the int4 patch (int4_kv): with VLLM_QUANTPACK_INT4_KV=0, or on a vLLM without the dtype registry, the
dtype is not registered and vLLM rejects the option.
"""
import torch

NAME = "k8v4_per_token_head"
SCALE_BYTES = 4


def cell_bytes(head_size, head_size_v):
    """Bytes of one (token, KV head) cell: int8 key, packed value, one fp32 scale each."""
    return head_size + head_size_v // 2 + 2 * SCALE_BYTES


def is_k8v4(key_cache):
    """True for the key view of a k8v4 cache (the int4 cache views are uint8)."""
    return key_cache.dtype == torch.int8


def views(kv_cache, head_size, head_size_v=None):
    """(key, value, key scale, value scale) views of the logical (blocks, KV heads, block size, cell) int8 cache.

    key (blocks, block size, KV heads, hs) int8; value (..., hs_v / 2) uint8; scales (blocks, block size, KV heads)
    fp32 over the same storage. The cache may be physically NHD: only its strides are used."""
    head_size_v = head_size if head_size_v is None else head_size_v
    nblocks, nkv, block_size, cell = kv_cache.shape
    if kv_cache.element_size() != 1 or cell != cell_bytes(head_size, head_size_v):
        raise ValueError(f"{NAME}: cache cell of {cell} x {kv_cache.element_size()} bytes, expected "
                         f"{cell_bytes(head_size, head_size_v)} for head sizes {head_size} / {head_size_v}")
    v_at = head_size + SCALE_BYTES
    t = kv_cache.transpose(1, 2)
    key = t[..., :head_size]
    value = t[..., v_at:v_at + head_size_v // 2].view(torch.uint8)
    st = kv_cache.stride()
    if any(s % 4 for s in st[:3]) or kv_cache.storage_offset() % 4 or head_size % 4 or (head_size_v // 2) % 4:
        raise ValueError(f"{NAME}: fp32 scales are not 4-byte aligned (strides {tuple(st)}, head {head_size})")
    base = torch.tensor([], dtype=torch.float32, device=kv_cache.device).set_(kv_cache.untyped_storage())
    off = kv_cache.storage_offset() // 4

    def scales(byte_at):
        return torch.as_strided(base, (nblocks, block_size, nkv), (st[0] // 4, st[2] // 4, st[1] // 4),
                                off + byte_at // 4)

    return key, value, scales(head_size), scales(v_at + head_size_v // 2)


def store(stock, key, value, key_cache, value_cache, slot_mapping, *, k_scale_cache, v_scale_cache):
    """Rotate (RHT, as the int4 cache), quantize and write key / value into the k8v4 cache views."""
    from .k8v4_ops import _store_k8v4 as kernel, triton
    key = stock.single_rht(key.float()).to(key.dtype)
    value = stock.single_rht(value.float()).to(value.dtype)
    num_tokens, num_kv_heads, head_size = key.shape
    head_size_v = value.shape[2]
    if head_size_v % 2:
        raise ValueError(f"{NAME}: odd value head size {head_size_v}")
    padded = triton.next_power_of_2(max(head_size, head_size_v))
    kernel[(num_tokens, num_kv_heads)](
        key, value, key_cache, value_cache, k_scale_cache, v_scale_cache, slot_mapping,
        key.stride(0), key.stride(1), value.stride(0), value.stride(1),
        key_cache.stride(0), key_cache.stride(1), key_cache.stride(2),
        value_cache.stride(0), value_cache.stride(1), value_cache.stride(2),
        k_scale_cache.stride(0), k_scale_cache.stride(1), k_scale_cache.stride(2),
        v_scale_cache.stride(0), v_scale_cache.stride(1), v_scale_cache.stride(2),
        block_size=key_cache.shape[1], head_size=head_size, head_size_v=head_size_v,
        HEAD_PADDED=padded, HALF_PADDED=max(1, padded // 2), num_warps=min(16, max(1, padded // 64)))


def register_dtype(logger):
    """Make `--kv-cache-dtype k8v4_per_token_head` a valid option. False on a vLLM without the dtype registry."""
    try:
        from vllm.config import cache as cache_config
        from vllm.v1.kv_cache_interface import KVQuantMode
        registry, lookup = cache_config.register_kv_cache_dtype, cache_config.get_kv_cache_dtype_handler
        mode = KVQuantMode.INT4_PER_TOKEN_HEAD
    except Exception as e:
        logger.debug("vllm-quantpack: %s not registered (%s)", NAME, e)
        return False
    if lookup(NAME) is None:
        class Handler:
            name = NAME

            def torch_dtype(self):
                return torch.int8

            def quant_mode(self):
                return mode

        registry(NAME)(Handler)
    return True


def patch_backend(stock, logger):
    """Teach the Triton backend the k8v4 page cell and views, and the int4 store its key half."""
    try:
        from vllm.v1.attention.backends import triton_attn
        from vllm.v1.kv_cache_interface import KVQuantMode
        backend, impl = triton_attn.TritonAttentionBackend, triton_attn.TritonAttentionImpl
        stock_spec = backend.customize_spec.__func__
        stock_scales, stock_views = impl._ensure_scale_caches, impl._pth_key_value_caches
        stock_store = stock.reshape_and_cache_int4
        supported = backend.supported_kv_cache_dtypes
    except Exception as e:
        logger.warning("vllm-quantpack: %s not available on this vLLM (%s)", NAME, e)
        return False
    if getattr(stock_store, "_quantpack", False):
        return True

    def customize_spec(cls, spec):
        if (spec.state_content_bytes is None and spec.kv_quant_mode == KVQuantMode.INT4_PER_TOKEN_HEAD
                and spec.dtype == torch.int8):
            from dataclasses import replace
            return replace(spec, state_content_bytes=cell_bytes(spec.head_size, spec.head_size_v))
        return stock_spec(cls, spec)

    def _ensure_scale_caches(self, kv_cache):
        if self.kv_cache_dtype != NAME:
            return stock_scales(self, kv_cache)
        if self._k_scale_cache is None:
            _, _, ks, vs = views(kv_cache, self.head_size)
            ks.fill_(1.0)
            vs.fill_(1.0)
            self._k_scale_cache, self._v_scale_cache = ks, vs

    def _pth_key_value_caches(self, kv_cache):
        if self.kv_cache_dtype != NAME:
            return stock_views(self, kv_cache)
        self._ensure_scale_caches(kv_cache)
        key, value, _, _ = views(kv_cache, self.head_size)
        return key, value

    def reshape_and_cache_int4(key, value, key_cache, value_cache, slot_mapping, *, k_scale_cache, v_scale_cache):
        if not is_k8v4(key_cache):
            return stock_store(key, value, key_cache, value_cache, slot_mapping, k_scale_cache=k_scale_cache,
                               v_scale_cache=v_scale_cache)
        store(stock, key, value, key_cache, value_cache, slot_mapping, k_scale_cache=k_scale_cache,
              v_scale_cache=v_scale_cache)

    reshape_and_cache_int4._quantpack = True
    backend.customize_spec = classmethod(customize_spec)
    impl._ensure_scale_caches = _ensure_scale_caches
    impl._pth_key_value_caches = _pth_key_value_caches
    stock.reshape_and_cache_int4 = reshape_and_cache_int4   # looked up in the module at call time
    if NAME not in supported:
        supported.append(NAME)
    return True
